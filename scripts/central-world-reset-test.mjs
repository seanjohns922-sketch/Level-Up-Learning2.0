import assert from 'node:assert/strict';
import { freshCentralWorldLayout, DEFAULT_HOME_PLACEMENT, readCentralWorldPlacements, readCentralWorldGroundTiles, writeCentralWorldPlacements, writeCentralWorldGroundTiles } from '../lib/world3d/central-world-layout.ts';
const storage = new Map([['owned-items', '["castle"]'], ['xp', '250']]);
globalThis.window = {localStorage: {getItem: key => storage.get(key) ?? null, setItem: (key,value) => storage.set(key,value)}};
const home = {...DEFAULT_HOME_PLACEMENT, gridX:12, gridZ:4, rotation:90};
const previous = {placements:[home,{itemId:'castle',placementId:'castle-one',gridX:20,gridZ:15,rotation:0}],tiles:[{gridX:2,gridZ:3,tileType:'water'}]};
writeCentralWorldPlacements('other-student', previous.placements);
writeCentralWorldGroundTiles('other-student', previous.tiles);
const fresh = freshCentralWorldLayout(previous.placements);
assert.deepEqual(fresh, {placements:[home],tiles:[]});
assert.notEqual(fresh.placements[0],home,'Reset does not mutate the undo snapshot');
writeCentralWorldPlacements('student',fresh.placements);
writeCentralWorldGroundTiles('student',fresh.tiles);
assert.deepEqual(readCentralWorldPlacements('student'),[home],'Moved home survives reload');
assert.deepEqual(readCentralWorldGroundTiles('student'),[],'Reload does not recreate starter paths');
assert.deepEqual(readCentralWorldPlacements('other-student'),[previous.placements[1], home],'Other scopes remain untouched');
assert.deepEqual(readCentralWorldGroundTiles('other-student'),previous.tiles);
writeCentralWorldPlacements('student',previous.placements);
writeCentralWorldGroundTiles('student',previous.tiles);
assert.deepEqual(readCentralWorldPlacements('student'),[previous.placements[1], home],'Undo restores all placed items');
assert.deepEqual(readCentralWorldGroundTiles('student'),previous.tiles,'Undo restores painted ground');
assert.equal(storage.get('owned-items'),'["castle"]');
assert.equal(storage.get('xp'),'250');
assert.deepEqual(freshCentralWorldLayout([]).placements,[DEFAULT_HOME_PLACEMENT],'Empty layouts keep the default home');
console.log('Start fresh: home, reload, undo, scope isolation and economy preservation passed.');
